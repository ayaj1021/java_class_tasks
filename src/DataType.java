public class DataType {

    public static  void main(String [] args){


        int number = 100;
        long numberOne = 200L;
        float scoreAverage = 50.5f;
        double amount = 233.00;
        char data = 'a';
        boolean isLoaded = true;
        String userName = "John";
        System.out.println("Number is " + number);
        System.out.println("Number one value is " + numberOne);
        System.out.println("Average score is " + scoreAverage);
        System.out.println("The item price is " + amount);
        System.out.println("The character is " + data);
        System.out.println("Is gun loaded: " + isLoaded);
        System.out.println("His name is " + userName);
        number = 150;
        numberOne = 2000L;
        scoreAverage = 60.7f;
        amount = 500.50;
        data = 'c';
        isLoaded = false;
        userName = "Peter";
        System.out.println("***********************");
        System.out.println("New number is " + number);
        System.out.println("New number one value is " + numberOne);
        System.out.println("New average score is " + scoreAverage);
        System.out.println("Updated item price is " + amount);
        System.out.println("The new character is " + data);
        System.out.println("Is gun loaded: " + isLoaded);
        System.out.println("His new name is " + userName);





    }
}


